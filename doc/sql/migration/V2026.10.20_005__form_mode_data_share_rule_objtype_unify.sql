--   映射：人员 1→4 | 部门 2→2 | 角色 3→1 | 岗位 4→3
--   （1..4 为排列，CASE 同批计算，无中间态冲突）
--
-- ⚠️ 幂等性：本表由 V2026.10.20_004 新建，正常无存量数据；
--    值域 1..4 在新旧两方案下均被占用，无法按值区分是否已迁移，
--    故本脚本**不可重复执行**（依赖迁移框架按版本号仅应用一次）。

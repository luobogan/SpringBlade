UPDATE `modedatasharerule`
SET `objtype` = CASE `objtype`
    WHEN 1 THEN 4  -- 人员 → 4
    WHEN 2 THEN 2  -- 部门 → 2（不变）
    WHEN 3 THEN 1  -- 角色 → 1
    WHEN 4 THEN 3  -- 岗位 → 3
    ELSE `objtype`
END
WHERE `objtype` IS NOT NULL;

